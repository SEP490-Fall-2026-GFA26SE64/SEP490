import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import type { ResearchRun } from '../src/features/administration/research/researchApi'

test('RQ2 latency shows one seed per page and retains all exported results', async ({ page, request }) => {
  test.setTimeout(300_000)
  const response = await request.get('/api/v1/admin/research/runs', { headers: { 'X-User-Id': 'admin.elena@adaptlearn.internal', 'X-User-Role': 'ADMIN' } })
  expect(response.ok()).toBe(true)
  const runs: ResearchRun[] = await response.json()
  const run = runs.slice(0, 5).find(r => r.status === 'SUCCEEDED' && new Set(r.results.map(result => result.trial?.seed ?? r.seed)).size > 1)
  test.skip(!run, 'Requires an existing multi-seed study in the first five history rows; no benchmark is generated by this UI test.')
  if (!run) return
  const seeds = [...new Set(run.results.map(result => result.trial?.seed ?? run.seed))]
  await page.goto('/login')
  await page.getByRole('button', { name: 'Admin', exact: true }).click()
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'Research', exact: true }).click()
  await page.getByRole('button', { name: `View run ${run.id}`, exact: true }).click()
  const section = page.getByRole('region', { name: 'Latency results by seed', exact: true })
  const cells = section.locator('tbody tr td:first-child')
  const expectedRows = (seed: number) => run.results.filter(r => (r.trial?.seed ?? run.seed) === seed).reduce((n,r) => n + 1 + Object.keys(r.byHop).length, 0)
  await expect(section.getByText(`Seed ${seeds[0]}`, { exact: true })).toBeVisible()
  await expect(cells).toHaveText(Array(expectedRows(seeds[0])).fill(String(seeds[0])))
  await expect(section.getByRole('button', { name: 'Previous page', exact: true })).toBeDisabled()
  await section.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(section.getByText(`Seed ${seeds[1]}`, { exact: true })).toBeVisible()
  await expect(cells).toHaveText(Array(expectedRows(seeds[1])).fill(String(seeds[1])))
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'JSON', exact: true }).click()
  const file = test.info().outputPath('all-seeds.json')
  await (await download).saveAs(file)
  const raw = JSON.parse(await readFile(file, 'utf8'))
  expect(raw.results).toHaveLength(run.results.length)
  expect([...new Set(raw.results.map((r: { trial: { seed: number } }) => r.trial.seed))]).toEqual(seeds)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await section.scrollIntoViewIfNeeded()
  await section.screenshot({ path: test.info().outputPath('seed-page-desktop.png') })
  await page.setViewportSize({ width: 375, height: 812 })
  await section.getByRole('region', { name: 'Latency seed pagination' }).scrollIntoViewIfNeeded()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('seed-page-mobile.png') })
  await page.reload()
  await page.getByRole('button', { name: `View run ${run.id}`, exact: true }).click({ timeout: 60_000 })
  await expect(section.getByText(`Seed ${seeds[0]}`, { exact: true })).toBeVisible()
})
