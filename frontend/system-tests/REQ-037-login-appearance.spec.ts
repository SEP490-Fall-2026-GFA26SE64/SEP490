import { expect, test, type Page } from '@playwright/test'
import { fixture, mutate, observe, record, totp } from './subscriptionHelpers'

test.use({ trace: 'off', screenshot: 'off', video: 'off' })
test.setTimeout(90000)

test.beforeEach(async ({ page, baseURL }) => {
  if (baseURL !== 'http://127.0.0.1:8092') throw new Error('This spec requires the isolated subscription test stack at port 8092.')
  await page.addInitScript(() => localStorage.setItem('app_language', 'en'))
})

async function assertNoOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

test('restores original illustrated login at desktop and mobile without demo authority', async ({ page }, testInfo) => {
  const observed = observe(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/login')
  await expect(page.getByRole('heading', { name: 'Enterprise Sign In', exact: true })).toBeVisible()
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('')
  const card = page.locator('.razor-card')
  await expect(card).toHaveCSS('border-radius', '42px')
  const bounds = await card.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.width).toBeCloseTo(580, 0)
  expect(bounds!.x + bounds!.width / 2).toBeCloseTo(720, 0)
  for (const selector of ['.razor-illustration-left img', '.razor-illustration-right img']) {
    const image = page.locator(selector)
    await expect(image).toBeVisible()
    await expect.poll(() => image.evaluate(element => element instanceof HTMLImageElement && element.complete && element.naturalWidth > 0)).toBe(true)
    await expect(image).toHaveAttribute('alt', '')
  }
  await expect(page.locator('.razor-demo-strip')).toHaveCount(0)
  await expect(page.getByText('Sign Up as Guest')).toHaveCount(0)
  const color = await page.getByRole('button', { name: 'Sign in', exact: true }).evaluate(element => {
    const probe = document.createElement('span')
    probe.style.backgroundColor = 'hsl(var(--primary))'
    element.appendChild(probe)
    const matches = getComputedStyle(probe).backgroundColor === getComputedStyle(element).backgroundColor
    probe.remove()
    return matches
  })
  expect(color).toBe(true)
  await assertNoOverflow(page)
  await page.screenshot({ path: testInfo.outputPath('enterprise-login-desktop.png'), fullPage: true })
  await page.getByLabel('Email', { exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Password', { exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Show password', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text')
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.razor-illustration-left')).toBeHidden()
  await expect(card).toHaveCSS('border-radius', '28px')
  await assertNoOverflow(page)
  await page.getByRole('button', { name: 'VI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Đăng nhập doanh nghiệp', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Hiện mật khẩu', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('enterprise-login-mobile-vi.png'), fullPage: true })
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.setViewportSize({ width: 844, height: 390 })
  await assertNoOverflow(page)
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
})

test('original login keeps real invalid-password, MFA, recovery and session-reload behavior', async ({ page }, testInfo) => {
  const observed = observe(page)
  const statuses: { path: string; status: number }[] = []
  page.on('response', response => {
    if (response.url().includes('/api/v1/') && response.status() >= 400) {
      statuses.push({ path: new URL(response.url()).pathname, status: response.status() })
    }
  })
  const account = await fixture(page.request, true)
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByLabel('Password', { exact: true }).fill('incorrect-isolated-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('.razor-card [role="alert"]')).toContainText('Email or password is incorrect')
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue(account.email)
  await page.getByLabel('Password', { exact: true }).fill(account.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByLabel('Authenticator code', { exact: true })).toBeVisible()
  await expect(page.locator('.razor-card')).toContainText('Authenticator code')
  expect((await page.request.get('/api/v1/platform/subscription-plans')).status()).toBe(401)
  await page.getByRole('button', { name: 'Use recovery code', exact: true }).click()
  await page.getByLabel('Recovery code', { exact: true }).fill('f'.repeat(32))
  await page.getByRole('button', { name: 'Verify', exact: true }).click()
  await expect(page.locator('.razor-card [role="alert"]')).toContainText('invalid or has already been used')
  await page.getByLabel('Recovery code', { exact: true }).fill('')
  await page.setViewportSize({ width: 390, height: 844 })
  await assertNoOverflow(page)
  await page.screenshot({ path: testInfo.outputPath('enterprise-login-recovery-error-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Use authenticator', exact: true }).click()
  await page.getByLabel('Authenticator code', { exact: true }).fill(totp(account.totpSecret))
  await page.getByRole('button', { name: 'Verify', exact: true }).click()
  await expect(page.getByText('Authentication complete.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Authentication complete.', { exact: true })).toBeVisible()
  expect((await page.request.get('/api/v1/platform/subscription-plans')).status()).toBe(200)
  const current = record(await (await page.request.get('/api/v1/workspace-auth/current')).json())
  expect(current.accountId).toBe(account.accountId)
  expect(current.stage).toBe('COMPLETE')
  const cookies = await page.context().cookies()
  const session = cookies.find(cookie => cookie.name === 'WORKSPACE_SESSION')
  expect(session?.httpOnly).toBe(true)
  expect(session?.sameSite).toBe('Lax')
  expect(session?.path).toBe('/api/v1')
  expect(await page.evaluate(() => [localStorage.getItem('auth_user'), localStorage.getItem('active_actor')])).toEqual([null, null])
  const signOut = await mutate(page.request, '/api/v1/workspace-auth/sign-out', {})
  expect(signOut.status()).toBe(204)
  expect((await page.request.get('/api/v1/workspace-auth/current')).status()).toBe(401)
  await page.reload()
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('')
  expect(statuses.some(value => value.path.endsWith('/sign-in') && value.status === 401)).toBe(true)
  expect(statuses.some(value => value.path.endsWith('/recovery') && value.status === 400)).toBe(true)
  expect(statuses.filter(value => value.status >= 500)).toEqual([])
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
})
