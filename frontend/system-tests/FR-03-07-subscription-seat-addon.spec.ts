import { expect, test, type Page } from '@playwright/test'
import { confirmPayment, fixture, mutate, observe, paymentEmails, purchase, record, registrationSession, text } from './subscriptionHelpers'

test.setTimeout(240000)
test.beforeEach(async ({ page }) => page.addInitScript(() => localStorage.setItem('app_language', 'en')))

async function summary(page: Page, org: string) {
  const response = await page.request.get(`/api/v1/organizations/${org}/subscription`)
  expect(response.ok()).toBeTruthy()
  return record(await response.json())
}
async function latestOrder(page: Page, org: string, kind: string) {
  const history = (await summary(page, org)).paymentHistory
  if (!Array.isArray(history)) throw new Error('Invalid payment history')
  const order = history.map(record).filter(item => item.kind === kind).sort((a, b) => text(b.createdAt).localeCompare(text(a.createdAt)))[0]
  if (!order) throw new Error(`No ${kind} order`)
  return order
}
async function buySeats(page: Page, seats: string | null) {
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  if (seats !== null) await dialog.getByRole('spinbutton').fill(seats)
  await dialog.getByRole('button', { name: 'Calculate price' }).click()
  await expect(dialog.getByTestId('seat-addon-quote')).toBeVisible()
  await dialog.getByRole('button', { name: 'Create payment order' }).click()
  await expect(page).toHaveURL(/\/admin\/subscription\/payment-result\?order=/, { timeout: 30000 })
  const orderId = new URL(page.url()).searchParams.get('order')
  if (!orderId) throw new Error('No seat add-on order id')
  return orderId
}

test('Organization Administrator buys, keeps, reduces and renews additional Employee seats', async ({ page }, testInfo) => {
  const observed = observe(page)
  const owner = await fixture(page.request)
  await registrationSession(page, owner)
  await confirmPayment(page, await purchase(page))
  await page.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(page.getByText('Current subscription period', { exact: true })).toBeVisible()
  const org = text(record(await (await page.request.get('/api/v1/workspace-auth/current')).json()).organizationId)
  await page.goto('/admin/subscription')
  const initial = await summary(page, org)
  const planSeats = Number(record(record(initial.current).terms).employeeSeats)
  const planPrice = Number(record(record(initial.current).terms).priceVnd)
  expect(record(initial.current).addonSeats).toBe(0)
  expect(initial.desiredAddonSeats).toBe(0)
  await expect(page.getByRole('button', { name: 'Reduce at renewal' })).toBeDisabled()

  // Invalid quantity is rejected before any request, then a valid purchase is quoted and ordered.
  await page.getByRole('button', { name: 'Buy extra seats' }).click()
  const dialog = page.getByRole('dialog', { name: 'Buy extra Employee seats' })
  await dialog.getByRole('spinbutton').fill('51')
  await expect(dialog.getByRole('alert')).toContainText('1 to 50')
  await expect(dialog.getByRole('button', { name: 'Calculate price' })).toBeDisabled()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('seat-addon-invalid-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  const increase = await buySeats(page, '2')
  await expect(page.getByRole('link', { name: 'Open payOS checkout' })).toBeVisible({ timeout: 30000 })
  const pending = await latestOrder(page, org, 'SEAT_ADDON')
  expect(pending.orderId).toBe(increase)
  expect(pending.addonSeats).toBe(2)
  expect(pending.seatAddonKind).toBe('INCREASE')
  expect((await summary(page, org)).seatChangeBlocked).toBe(true)
  await page.goto('/admin/subscription')
  await expect(page.getByRole('button', { name: 'Buy extra seats' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Renew subscription', exact: true })).toBeDisabled()
  await expect(page.getByText(/Seat changes are unavailable while a renewal or seat payment is unresolved/)).toBeVisible()

  await confirmPayment(page, increase)
  await expect.poll(async () => record((await summary(page, org)).current).addonSeats, { timeout: 30000 }).toBe(2)
  await page.reload()
  const figures = page.getByLabel('Current period seats')
  await expect(figures).toContainText(`Included in plan${planSeats}`)
  await expect(figures).toContainText('Additional seats2')
  await expect(figures).toContainText(`Total this period${planSeats + 2}`)
  await expect(page.getByTestId('desired-addon-seats')).toContainText('2')
  const afterIncrease = await summary(page, org)
  expect(afterIncrease.allocatedSeats).toBe(planSeats + 2)
  expect(afterIncrease.seatChangeBlocked).toBe(false)
  await expect.poll(async () => {
    const mails = await paymentEmails(page.request, owner.email)
    const bodies = await Promise.all(mails.map(async message =>
      text(record(await (await page.request.get(`http://127.0.0.1:8029/api/v1/message/${text(message.ID)}`)).json()).Text)))
    return bodies.some(body => body.includes('Additional Employee seats') && body.includes(increase))
  }, { timeout: 30000 }).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('seat-addon-applied-desktop.png'), fullPage: true })

  // Reduction applies to the next renewal and persists.
  await page.getByRole('button', { name: 'Reduce at renewal' }).click()
  const reduce = page.getByRole('dialog', { name: 'Reduce additional seats at renewal' })
  await reduce.getByRole('spinbutton').fill('1')
  await reduce.getByRole('button', { name: 'Save reduction' }).click()
  await expect(reduce).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId('desired-addon-seats')).toContainText('1')
  const reduced = await summary(page, org)
  expect(reduced.desiredAddonSeats).toBe(1)
  expect(record(reduced.current).addonSeats).toBe(2)

  // A same-plan renewal includes the kept additional seat at the full-period seat price.
  await page.getByRole('button', { name: 'Renew subscription', exact: true }).click()
  await page.getByRole('button', { name: 'Select Starter', exact: true }).click()
  await expect(page.getByTestId('renewal-addon')).toContainText('+1 additional seat(s)')
  await page.getByRole('dialog').getByRole('button', { name: 'Create payment order' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Open payOS checkout' })).toBeVisible({ timeout: 30000 })
  const renewal = record(record(await (await page.request.get(`/api/v1/organizations/${org}/subscription/current-order`)).json()).order)
  expect(renewal.addonSeats).toBe(1)
  expect(renewal.addonAmountVnd).toBe(Math.ceil(planPrice / planSeats))
  expect(record(renewal.terms).priceVnd).toBe(planPrice + Math.ceil(planPrice / planSeats))
  await confirmPayment(page, text(renewal.orderId))
  await expect.poll(async () => (await summary(page, org)).scheduled !== null, { timeout: 30000 }).toBe(true)
  const scheduled = record((await summary(page, org)).scheduled)
  expect(scheduled.addonSeats).toBe(1)
  expect(scheduled.totalSeats).toBe(planSeats + 1)

  // Buying more while a period is scheduled covers the current period and leaves a scheduled-period shortfall to pay.
  await page.reload()
  await page.getByRole('button', { name: 'Buy extra seats' }).click()
  await expect(page.getByRole('dialog')).toContainText('A next period is already scheduled')
  const second = await buySeats(page, '1')
  await confirmPayment(page, second)
  await expect.poll(async () => (await summary(page, org)).scheduledShortfall, { timeout: 30000 }).toBe(1)
  const withShortfall = await summary(page, org)
  expect(withShortfall.desiredAddonSeats).toBe(2)
  expect(record(withShortfall.current).addonSeats).toBe(3)
  expect(withShortfall.admissionLimit).toBe(planSeats + 1)
  await page.goto('/admin/subscription')
  await expect(page.getByText('The scheduled period is missing 1 additional seat(s).', { exact: false })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('seat-addon-shortfall-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Pay for the scheduled period' }).click()
  await expect(page.getByRole('dialog').getByRole('spinbutton')).toBeDisabled()
  const shortfall = await buySeats(page, null)
  const shortfallOrder = await latestOrder(page, org, 'SEAT_ADDON')
  expect(shortfallOrder.orderId).toBe(shortfall)
  expect(shortfallOrder.seatAddonKind).toBe('SHORTFALL')
  expect(record(shortfallOrder.terms).priceVnd).toBe(Math.ceil(planPrice / planSeats))
  await confirmPayment(page, shortfall)
  await expect.poll(async () => (await summary(page, org)).scheduledShortfall, { timeout: 30000 }).toBe(0)
  const final = await summary(page, org)
  expect(record(final.scheduled).totalSeats).toBe(planSeats + 2)
  expect(final.admissionLimit).toBe(planSeats + 2)
  await page.goto('/admin/subscription')
  await expect(page.getByText(/is missing .* additional seat/)).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('seat-addon-final-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await expect(page.getByLabel('Current period seats')).toContainText(`Total this period${planSeats + 3}`)
  await page.screenshot({ path: testInfo.outputPath('seat-addon-final-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Buy extra seats' }).click()
  await page.screenshot({ path: testInfo.outputPath('seat-addon-dialog-mobile.png') })
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
})

test('Another organization administrator cannot quote, buy or reduce seats for a foreign organization', async ({ page, browser }) => {
  await registrationSession(page, await fixture(page.request))
  await confirmPayment(page, await purchase(page))
  await page.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(page.getByText('Current subscription period', { exact: true })).toBeVisible()
  const org = text(record(await (await page.request.get('/api/v1/workspace-auth/current')).json()).organizationId)
  const otherContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8092' })
  const other = await otherContext.newPage()
  await other.addInitScript(() => localStorage.setItem('app_language', 'en'))
  await registrationSession(other, await fixture(other.request))
  await confirmPayment(other, await purchase(other))
  await other.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(other.getByText('Current subscription period', { exact: true })).toBeVisible()
  expect((await other.request.get(`/api/v1/organizations/${org}/subscription/seat-addons/quote?target=CURRENT&seats=1`)).status()).toBe(403)
  expect((await mutate(other.request, `/api/v1/organizations/${org}/subscription/seat-addons/orders`,
    { idempotencyKey: crypto.randomUUID(), seats: 1, target: 'CURRENT', expectedAmountVnd: 1 })).status()).toBe(403)
  expect((await mutate(other.request, `/api/v1/organizations/${org}/subscription/seat-addons`,
    { desiredAddonSeats: 0, expectedDesiredAddonSeats: 0 }, 'PUT')).status()).toBe(403)
  expect((await page.request.get(`/api/v1/organizations/${org}/subscription/seat-addons/quote?target=CURRENT&seats=51`)).status()).toBe(400)
  const own = record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json())
  expect(own.desiredAddonSeats).toBe(0)
  expect(own.paymentHistory).toHaveLength(1)
  await otherContext.close()
})
