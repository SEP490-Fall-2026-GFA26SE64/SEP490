import { expect, test } from '@playwright/test'
import { confirmPayment, fixture, observe, purchase, record, registrationSession, text, paymentEmails as messages } from './subscriptionHelpers'

const inbox = 'http://127.0.0.1:8029'
test.setTimeout(120000)
test.beforeEach(async ({ page, baseURL }) => {
  if (baseURL !== 'http://127.0.0.1:8092') throw new Error('Use only the isolated subscription test stack.')
  await page.addInitScript(() => localStorage.setItem('app_language', 'en'))
})

test('Verified payment produces one branded purchaser email and an owner-scoped reloadable receipt', async ({ page, browser }, testInfo) => {
  const observed = observe(page)
  const owner = await fixture(page.request)
  await registrationSession(page, owner)
  const orderId = await purchase(page)
  await page.goto(`/guest/payment-result?order=${orderId}&status=PAID&success=true`)
  await expect(page.getByText('Payment confirmed', { exact: true })).toHaveCount(0)
  expect(await messages(page.request, owner.email)).toHaveLength(0)
  const signed = await confirmPayment(page, orderId)
  await expect(page.getByText('Payment confirmed', { exact: true })).toBeVisible({ timeout: 30000 })
  const result = record(await (await page.request.get(`/api/v1/registration/subscription/orders/${orderId}`)).json())
  const order = record(result.order)
  await expect(page.getByText(String(order.providerOrderCode), { exact: true })).toBeVisible()
  await expect(page.getByText('System confirmation time', { exact: true })).toBeVisible()
  expect(order.confirmedAt).not.toBeNull()
  await expect.poll(async () => (await messages(page.request, owner.email)).length, { timeout: 30000 }).toBe(1)
  const entry = (await messages(page.request, owner.email))[0]
  const mail = record(await (await page.request.get(`${inbox}/api/v1/message/${text(entry.ID)}`)).json())
  expect(text(mail.Text)).toContain(orderId)
  expect(text(mail.Text)).toContain('Starter')
  expect(text(mail.Text)).toContain('4,900,000 VND')
  expect(text(mail.HTML)).toContain('Adapt-Learn-Graph')
  expect(text(mail.HTML)).toContain('<table')
  expect(text(mail.HTML)).toContain(`/guest/payment-result?order=${orderId}`)
  const emailPage = await page.context().newPage()
  await emailPage.setViewportSize({ width: 390, height: 844 })
  await emailPage.setContent(text(mail.HTML))
  await expect(emailPage.getByRole('link', { name: 'View payment details', exact: true })).toBeVisible()
  expect(await emailPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await emailPage.screenshot({ path: testInfo.outputPath('payment-email-mobile.png'), fullPage: true })
  await emailPage.close()
  await page.request.post('/api/v1/payments/payos/webhook', { data: signed })
  await page.reload()
  await expect(page.getByText('Payment confirmed', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('payment-result-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'VI', exact: true }).click()
  await expect(page.getByText('Đã xác nhận thanh toán', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('payment-result-mobile-vi.png'), fullPage: true })
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.getByRole('button', { name: 'Enter workspace', exact: true }).click()
  await page.goto(`/admin/subscription/payment-result?order=${orderId}`)
  await expect(page.getByText(String(order.providerOrderCode), { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Payment confirmed', { exact: true })).toBeVisible()
  expect(await messages(page.request, owner.email)).toHaveLength(1)
  const stranger = await browser.newContext({ baseURL: 'http://127.0.0.1:8092' })
  expect((await stranger.request.get(`/api/v1/subscription/orders/${orderId}`)).status()).toBe(401)
  const strangerPage = await stranger.newPage()
  await registrationSession(strangerPage, await fixture(stranger.request))
  expect((await stranger.request.get(`/api/v1/registration/subscription/orders/${orderId}`)).status()).toBe(403)
  await stranger.close()
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
})
