import { expect, test } from '@playwright/test'
import { activationLink, confirmPayment, fixture, mutate, observe, purchase, record, registrationSession, text, workspaceLogin, paymentEmails } from './subscriptionHelpers'

test.setTimeout(120000)
test.beforeEach(async ({ page }) => page.addInitScript(() => localStorage.setItem('app_language', 'en')))
test('Organization renewal appends one paid future period and reloads persisted history', async ({ page }, testInfo) => {
  const observed = observe(page)
  const purchaser = await fixture(page.request)
  await registrationSession(page, purchaser)
  const initial = await purchase(page)
  await confirmPayment(page, initial)
  await expect(page.getByRole('button', { name: 'Enter workspace' })).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: 'Enter workspace' }).click()
  await expect(page.getByRole('button', { name: 'Renew subscription', exact: true })).toBeEnabled()
  const identity = record(await (await page.request.get('/api/v1/workspace-auth/current')).json())
  const org = text(identity.organizationId)
  const before = record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json())
  await page.getByRole('button', { name: 'Renew subscription', exact: true }).click()
  await page.getByRole('button', { name: 'Select Starter', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Create payment order' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Open payOS checkout' })).toBeVisible({ timeout: 30000 })
  const current = record(await (await page.request.get(`/api/v1/organizations/${org}/subscription/current-order`)).json())
  const renewal = text(record(current.order).orderId)
  await confirmPayment(page, renewal)
  await expect(page.getByText('Scheduled paid period', { exact: true })).toBeVisible({ timeout: 30000 })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Renew subscription', exact: true })).toBeDisabled()
  const after = record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json())
  expect(record(after.current).endsAt).toBe(record(before.current).endsAt)
  expect(record(after.scheduled).startsAt).toBe(record(before.current).endsAt)
  expect(Array.isArray(after.paymentHistory) && after.paymentHistory.length).toBe(2)
  await expect.poll(async () => (await paymentEmails(page.request, purchaser.email)).length, { timeout: 30000 }).toBe(2)
  const delivered = await paymentEmails(page.request, purchaser.email)
  const bodies = await Promise.all(delivered.map(async message =>
    record(await (await page.request.get(`http://127.0.0.1:8029/api/v1/message/${text(message.ID)}`)).json())))
  expect(bodies.some(message => text(message.Text).includes(`/admin/subscription/payment-result?order=${renewal}`))).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('organization-renewal-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('organization-renewal-mobile.png'), fullPage: true })
  await page.goto(`/admin/subscription/payment-result?order=${renewal}`)
  await expect(page.getByText('Payment confirmed', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Back to subscription', exact: true })).toBeVisible()
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
})

test('Employee activation uses captured email, requires assignments, consumes a seat and cannot cross organizations', async ({ page, browser }, testInfo) => {
  const account = await fixture(page.request)
  await registrationSession(page, account)
  const order = await purchase(page)
  await confirmPayment(page, order)
  await page.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(page.getByText('Current paid period', { exact: true })).toBeVisible()
  const identity = record(await (await page.request.get('/api/v1/workspace-auth/current')).json())
  const org = text(identity.organizationId)
  expect((await page.request.post(`/api/v1/__subscription-test/references/${org}`)).ok()).toBeTruthy()
  const referenceList: unknown = await (await page.request.get(`/api/v1/organizations/${org}/subscription/member-references`)).json()
  if (!Array.isArray(referenceList) || referenceList.length !== 1) throw new Error('Missing isolated assignment references')
  const assignedReference = record(referenceList[0])
  await page.goto('/admin/users')
  await expect(page.getByRole('heading', { name: 'User Accounts', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Create User', exact: true }).click()
  await page.getByLabel('Full name', { exact: true }).fill('Isolated Employee')
  const email = `${crypto.randomUUID()}@example.test`
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Department', { exact: true }).selectOption({ label: 'Test Department' })
  await page.getByLabel('Occupation', { exact: true }).selectOption({ label: 'Test Occupation' })
  await page.getByRole('button', { name: 'Send activation link' }).click()
  await expect(page.getByText('Activation email queued. Inbox delivery is not yet confirmed.', { exact: true })).toBeVisible()
  const link = await activationLink(page.request, email)
  const employeeContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8092' })
  const employee = await employeeContext.newPage()
  await employee.addInitScript(() => localStorage.setItem('app_language', 'en'))
  await employee.goto(link)
  await employee.getByLabel('Password', { exact: true }).fill('isolated employee password')
  await employee.getByLabel('Confirm password', { exact: true }).fill('isolated employee password')
  await employee.getByRole('button', { name: 'Activate account', exact: true }).click()
  await expect(employee.getByText('Account activated.', { exact: false })).toBeVisible()
  await employee.getByRole('link', { name: 'Sign in', exact: true }).click()
  await employee.getByLabel('Email', { exact: true }).fill(email)
  await employee.getByLabel('Password', { exact: true }).fill('isolated employee password')
  await employee.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(employee.getByText('Authentication complete.', { exact: true })).toBeVisible()
  await expect(employee.getByLabel('Authenticator code')).toHaveCount(0)
  expect((await employee.request.get(`/api/v1/organizations/${org}/subscription`)).status()).toBe(403)
  const otherContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8092' })
  const other = await otherContext.newPage()
  await other.addInitScript(() => localStorage.setItem('app_language', 'en'))
  await registrationSession(other, await fixture(other.request))
  const otherOrder = await purchase(other)
  await confirmPayment(other, otherOrder)
  await other.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(other.getByText('Current paid period', { exact: true })).toBeVisible()
  const otherIdentity = record(await (await other.request.get('/api/v1/workspace-auth/current')).json())
  const otherOrg = text(otherIdentity.organizationId)
  expect(otherOrg).not.toBe(org)
  for (const resource of ['target-roles', 'micro-skills', 'prerequisites', 'macro-competencies']) {
    expect((await employee.request.get(`/api/v1/organizations/${otherOrg}/${resource}`, {
      headers: { 'X-User-Role': 'LD_MANAGER', 'X-User-Id': account.accountId },
    })).status()).toBe(403)
  }
  const summary = record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json())
  expect(summary.usedSeats).toBe(1)
  const memberList: unknown = await (await page.request.get(`/api/v1/organizations/${org}/subscription/members`)).json()
  if (!Array.isArray(memberList)) throw new Error('Invalid persisted members')
  const saved = memberList.map(record).find(member => member.email === email)
  expect(saved?.fullName).toBe('Isolated Employee')
  expect(saved?.roles).toEqual(['EMPLOYEE'])
  expect(saved?.departmentId).toBe(assignedReference.departmentId)
  expect(saved?.occupationReferenceId).toBe(assignedReference.occupationReferenceId)
  expect(saved?.active).toBe(true)
  await employee.screenshot({ path: testInfo.outputPath('employee-password-only.png'), fullPage: true })
  await otherContext.close()
  await employeeContext.close()
})

test('Administrative suspension blocks renewal and protected APIs but retains truthful billing reads', async ({ page, browser }) => {
  const owner = await fixture(page.request)
  await registrationSession(page, owner)
  const order = await purchase(page)
  await confirmPayment(page, order)
  await page.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(page.getByText('Current paid period', { exact: true })).toBeVisible()
  const identity = record(await (await page.request.get('/api/v1/workspace-auth/current')).json())
  const org = text(identity.organizationId)
  const platformContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8092' })
  const platform = await platformContext.newPage()
  await platform.addInitScript(() => localStorage.setItem('app_language', 'en'))
  await workspaceLogin(platform, await fixture(platform.request, true))
  await platform.goto('/platform-admin/organizations')
  await expect(platform.getByRole('heading', { name: 'Workspace administration', exact: true })).toBeVisible()
  expect((await mutate(platform.request, `/api/v1/platform/workspaces/${org}/suspension`, { suspended: true }, 'PUT')).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByText('Suspended', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Renew subscription', exact: true })).toBeDisabled()
  expect((await page.request.get(`/api/v1/organizations/${org}/target-roles`)).status()).toBe(403)
  expect((await page.request.get('/api/v1/subscription/access')).status()).toBe(403)
  expect((await page.request.get(`/api/v1/organizations/${org}/subscription`)).status()).toBe(200)
  expect((await page.request.get(`/api/v1/organizations/${org}/subscription/members`)).status()).toBe(403)
  expect((await page.request.get(`/api/v1/organizations/${org}/subscription/activations`)).status()).toBe(403)
  expect((await mutate(platform.request, `/api/v1/platform/workspaces/${org}/suspension`, { suspended: false }, 'PUT')).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Renew subscription', exact: true })).toBeEnabled()
  await platformContext.close()
})
