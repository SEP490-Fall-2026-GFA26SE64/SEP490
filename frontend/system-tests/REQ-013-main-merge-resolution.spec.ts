import { expect as baseExpect, test, type APIRequestContext, type Page } from '@playwright/test'
const expect = baseExpect.configure({ timeout: 60_000 })
const root = '/api/v1/module-management'
type Member = { accountId: string; email: string; password: string }
type Fixture = { organizationId: string; occupationId: string; moduleId: string; expert: Member; manager: Member }
async function mutation(request: APIRequestContext, path: string, data: unknown, method = 'POST') {
  const csrf = await (await request.get('/api/v1/workspace-auth/csrf')).json() as { headerName: string; token: string }
  return request.fetch(path, { method, data, headers: { [csrf.headerName]: csrf.token } })
}
async function login(page: Page, member: Member, home: string) {
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.getByLabel('Email', { exact: true }).fill(member.email)
  await page.getByLabel('Password', { exact: true }).fill(member.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Continue to workspace', exact: true }).click()
  await page.goto(home, { waitUntil: 'domcontentloaded' })
}
test('merge: real role login, scoped module intake, CSRF, approval, reload and shared logout', async ({ page, request, browser, baseURL }) => {
  test.setTimeout(600_000)
  if (baseURL !== 'http://127.0.0.1:28188') throw new Error('Run only against the isolated merge-resolution-test stack.')
  await expect.poll(() => request.get('/api/v1/system/status').then(r => r.ok()).catch(() => false), { timeout: 120_000 }).toBeTruthy()
  const response = await request.post('/api/v1/__subscription-test/module-workspace')
  expect(response.status(), await response.text()).toBe(200)
  const fixture = await response.json() as Fixture
  const moduleCard = page.locator('div.bg-card').filter({ has: page.getByText(fixture.moduleId, { exact: true }) })
  expect((await request.get(root + '/session', { headers: { Cookie: 'baseline_demo_persona=ld', 'X-User-Role': 'LD_MANAGER' } })).status()).toBe(401)
  await page.addInitScript(() => localStorage.setItem('app_language', 'en'))
  await login(page, fixture.manager, '/ld-manager/modules')
  expect((await page.request.put(root + '/grants', { data: {} })).status()).toBe(403)
  expect((await mutation(page.request, root + '/grants', { expertId: fixture.expert.accountId, occupationId: fixture.occupationId, active: true }, 'PUT')).status()).toBe(204)
  await page.getByLabel('Search name or ID', { exact: true }).fill(fixture.moduleId)
  await moduleCard.getByRole('button', { name: 'Assign for intake', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Assign for intake' })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await moduleCard.getByRole('button', { name: 'Assign for intake', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Assign for intake' })
  await dialog.getByLabel('Related occupations', { exact: true }).selectOption(fixture.occupationId)
  await dialog.getByRole('button', { name: 'Assign', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(moduleCard.getByText('Awaiting Expert intake', { exact: true })).toBeVisible()
  await mutation(page.request, '/api/v1/workspace-auth/sign-out', {})
  await login(page, fixture.expert, '/expert/modules')
  await expect(page.getByRole('button', { name: 'User actions menu' })).toContainText('Merge DOMAIN_EXPERT')
  await page.getByLabel('Search name or ID', { exact: true }).fill(fixture.moduleId)
  await moduleCard.getByRole('button', { name: 'Receive for editing', exact: true }).click()
  await page.getByRole('dialog', { name: 'Receive for editing' }).getByRole('button', { name: 'Receive module', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Module editor' })
  await expect(editor.getByLabel('Title', { exact: true })).toHaveValue('Imported merge verification module')
  await editor.getByLabel('Title', { exact: true }).fill('Reviewed merge verification module')
  await editor.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(editor).not.toBeVisible()
  await moduleCard.getByRole('button', { name: 'Submit for review', exact: true }).click()
  await page.getByRole('dialog', { name: 'Submit for review' }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(moduleCard.getByText('Submitted', { exact: true })).toBeVisible()
  const other = await (await request.post('/api/v1/__subscription-test/module-workspace')).json() as Fixture
  const foreign = await browser.newContext({ baseURL })
  expect((await mutation(foreign.request, '/api/v1/workspace-auth/sign-in', { email: other.expert.email, password: other.expert.password })).status()).toBe(200)
  expect((await foreign.request.get(`${root}/modules/${fixture.moduleId}`)).status()).toBe(404)
  await foreign.close()
  await mutation(page.request, '/api/v1/workspace-auth/sign-out', {})
  await login(page, fixture.manager, '/ld-manager/approvals')
  await page.getByRole('navigation', { name: 'Learning workspace' }).getByRole('link', { name: 'Modules', exact: true }).click()
  await expect(page).toHaveURL(/\/ld-manager\/modules$/)
  await page.getByLabel('Search name or ID', { exact: true }).fill(fixture.moduleId)
  await moduleCard.getByRole('button', { name: 'Details & history', exact: true }).click()
  const history = page.getByRole('dialog', { name: 'Module details' })
  await expect(history.getByText('Created by / Responsible Expert: Merge DOMAIN_EXPERT', { exact: true })).toBeVisible()
  await expect(history.getByText('Received by: Merge DOMAIN_EXPERT', { exact: false })).toBeVisible()
  await history.getByRole('button', { name: 'Close dialog' }).click()
  await moduleCard.getByRole('button', { name: 'Approve and release', exact: true }).click()
  await page.getByRole('dialog', { name: 'Approve and release' }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(moduleCard.getByText('Released', { exact: true })).toBeVisible({ timeout: 60_000 })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByLabel('Search name or ID', { exact: true }).fill(fixture.moduleId)
  await expect(moduleCard.getByText('Released', { exact: true })).toBeVisible()
  const saved = await (await page.request.get(`${root}/modules/${fixture.moduleId}`)).json() as { createdBy: string; revisions: { decidedBy: string; state: string }[] }
  expect(saved.createdBy).toBe(fixture.expert.accountId); expect(saved.revisions.at(-1)?.decidedBy).toBe(fixture.manager.accountId)
  await page.evaluate(() => window.scrollTo({ top: 0, left: 0, behavior: 'instant' }))
  await page.screenshot({ path: 'test-results/REQ-013-main-merge-resolution.png', fullPage: true })
  await page.getByRole('button', { name: 'User actions menu' }).click()
  await page.getByRole('button', { name: 'Log Out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get(root + '/session')).status()).toBe(401)
  expect((await page.request.get('/api/v1/workspace-auth/current')).status()).toBe(401)
})
