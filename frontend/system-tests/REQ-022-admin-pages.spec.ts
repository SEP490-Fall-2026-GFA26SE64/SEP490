import { expect, test } from '@playwright/test'
import { activationLink, confirmPayment, fixture, mutate, observe, purchase, record, registrationSession, text } from './subscriptionHelpers'

test.setTimeout(150000)
test.beforeEach(async ({ page, baseURL }) => {
  if (!['http://127.0.0.1:8092', 'http://127.0.0.1:8093'].includes(baseURL ?? '')) throw new Error('Use the isolated subscription or identity-test stack.')
  await page.addInitScript(() => localStorage.setItem('app_language', 'en'))
})

test('Administrator layout separates billing from user CRUD, persists edits and retains demo navigation safely', async ({ page, browser }, testInfo) => {
  const observed = observe(page)
  const owner = await fixture(page.request)
  await registrationSession(page, owner)
  const order = await purchase(page)
  await confirmPayment(page, order)
  await page.getByRole('button', { name: 'Enter workspace' }).click({ timeout: 30000 })
  await expect(page.getByText('Current subscription period', { exact: true })).toBeVisible()
  await expect(page.locator('.workspace-sidebar')).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Portal feature tabs' }).getByRole('link', { name: 'Subscription', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('button', { name: 'Send activation link' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'User directory' })).toHaveCount(0)
  const identity = record(await (await page.request.get('/api/v1/workspace-auth/current')).json())
  const org = text(identity.organizationId)
  await page.request.post(`/api/v1/__subscription-test/references/${org}`)
  await page.screenshot({ path: testInfo.outputPath('administrator-subscription-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Manage users', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'User Accounts', exact: true })).toBeVisible()
  await page.goto('/admin/user')
  await expect(page).toHaveURL(/\/admin\/users$/)
  await expect(page.getByRole('heading', { name: 'User Accounts', exact: true })).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Portal feature tabs' })
  await expect(nav.getByRole('link', { name: 'User Accounts', exact: true })).toHaveAttribute('aria-current', 'page')
  const ownerRow = page.getByRole('row').filter({ hasText: owner.email })
  await expect(ownerRow.getByRole('button', { name: 'Deactivate', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Create User', exact: true }).click()
  const create = page.getByRole('dialog', { name: 'Create User', exact: true })
  await expect(create).toBeFocused()
  const email = `${crypto.randomUUID()}@example.test`
  await create.getByLabel('Full name', { exact: true }).fill('Directory Employee')
  await create.getByLabel('Email', { exact: true }).fill(email)
  await create.getByLabel('Department', { exact: true }).selectOption({ label: 'Test Department' })
  await create.getByLabel('Occupation', { exact: true }).selectOption({ label: 'Test Occupation' })
  await create.getByRole('button', { name: 'Send activation link', exact: true }).click()
  await expect(create).toHaveCount(0)
  const invited = page.getByRole('row').filter({ hasText: email })
  await expect(invited).toContainText('Awaiting activation')
  await page.reload()
  await expect(invited).toContainText('Directory Employee')
  await page.getByRole('textbox', { name: 'Search users' }).fill(email)
  await expect(ownerRow).toHaveCount(0)
  await expect(invited.getByRole('button', { name: 'Resend', exact: true })).toBeVisible()
  const link = await activationLink(page.request, email)
  const recipient = await browser.newContext({ baseURL: new URL(page.url()).origin })
  const token = new URLSearchParams(new URL(link).hash.slice(1)).get('token')
  expect((await mutate(recipient.request, '/api/v1/workspace-auth/activate', { token, password: 'isolated-directory-password' })).status()).toBe(200)
  await page.reload()
  const row = page.getByRole('row').filter({ hasText: email })
  await expect(row).toContainText('Active')
  await row.getByRole('button', { name: 'View', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'User details', exact: true })
  await expect(detail).toContainText('Test Department')
  await expect(detail).toContainText('Test Occupation')
  await detail.getByRole('button', { name: 'Close dialog' }).click()
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edit User', exact: true })
  await expect(edit.getByLabel('Email', { exact: true })).toHaveAttribute('readonly', '')
  await edit.getByLabel('Full name', { exact: true }).fill('Updated Directory Employee')
  await edit.getByRole('radio', { name: 'Expert', exact: true }).check()
  await edit.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(edit).toHaveCount(0)
  await page.reload()
  await expect(row).toContainText('Updated Directory Employee')
  await expect(row).toContainText('Expert')
  expect(record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json()).usedSeats).toBe(0)
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await edit.getByRole('radio', { name: 'Employee', exact: true }).check()
  await edit.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(edit).toHaveCount(0)
  await row.getByRole('button', { name: 'Deactivate', exact: true }).click()
  await page.getByRole('dialog', { name: 'Confirm membership change' }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Confirm membership change' })).toHaveCount(0)
  await expect(row).toContainText('Inactive')
  const after = record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json())
  expect(after.usedSeats).toBe(0)
  await row.getByRole('button', { name: 'Reactivate', exact: true }).click()
  await page.getByRole('dialog', { name: 'Confirm membership change' }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Confirm membership change' })).toHaveCount(0)
  await expect(row).toContainText('Active')
  expect(record(await (await page.request.get(`/api/v1/organizations/${org}/subscription`)).json()).usedSeats).toBe(1)
  await expect(page.getByText('1 / 20', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Filter by role' }).selectOption('EMPLOYEE')
  await expect(ownerRow).toHaveCount(0)
  await expect(row).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect(page.locator('.workspace-header')).toHaveCSS('top', '0px')
  await page.screenshot({ path: testInfo.outputPath('administrator-users-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Collapse sidebar' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'VI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tài khoản người dùng', exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('administrator-users-mobile-vi.png'), fullPage: true })
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.getByRole('button', { name: 'User actions menu', exact: true }).click()
  const menu = page.locator('.workspace-account-dropdown')
  await expect(menu).toContainText(owner.email)
  await expect(menu.getByRole('link', { name: 'Employee', exact: true })).toBeVisible()
  await expect(menu.getByRole('link', { name: 'Platform Admin', exact: true })).toBeVisible()
  await menu.getByRole('link', { name: 'Platform Admin', exact: true }).click()
  await expect(page.getByText('Your authenticated role cannot enter this workspace.', { exact: true })).toBeVisible()
  expect((await page.request.get('/api/v1/platform/subscription-plans')).status()).toBe(403)
  await page.goto('/admin/users')
  await page.getByRole('button', { name: 'User actions menu', exact: true }).click()
  await page.getByRole('button', { name: 'Log Out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/v1/workspace-auth/current')).status()).toBe(401)
  await recipient.close()
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
})
