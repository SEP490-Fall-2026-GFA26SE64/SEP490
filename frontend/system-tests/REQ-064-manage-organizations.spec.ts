test('Real directory search, status filters and pagination retain global metrics and trusted navigation', async ({ page }, testInfo) => {
  const fixtures: Record<string, unknown>[] = []
  for (let i = 0; i < 11; i++) {
    const response = await page.request.post('/api/v1/__subscription-test/organization-directory?coverage=NONE')
    expect(response.ok()).toBeTruthy()
    fixtures.push(record(await response.json()))
  }
  const platform = await fixture(page.request, true)
  await workspaceLogin(page, platform)
  const observed = observe(page)
  await expect(page).toHaveURL(/\/platform-admin\/organizations$/)
  await expect(page.getByRole('heading', { name: 'Organizations', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('platform-login-organizations.png'), fullPage: true })
  const response = await page.request.get('/api/v1/platform/workspaces')
  expect(response.ok()).toBeTruthy()
  const rows: unknown = await response.json()
  if (!Array.isArray(rows)) throw new Error('Invalid real directory')
  const overview = page.getByRole('region', { name: 'Organization overview' })
  await expect(overview).toBeVisible()
  const metrics = [
    rows.length,
    rows.map(record).filter(row => row.status === 'ACTIVE').length,
    rows.map(record).filter(row => row.status === 'SUSPENDED').length,
    rows.map(record).filter(row => record(row.subscription).status === 'ACTIVE').length,
  ].map(String)
  await expect(overview.getByRole('heading')).toHaveText(metrics)
  const dataRows = page.getByRole('table').locator('tbody tr')
  await expect(dataRows).toHaveCount(10)
  const firstPage = await dataRows.first().getAttribute('aria-label')
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(dataRows.first()).not.toHaveAttribute('aria-label', firstPage ?? '')
  const search = page.getByRole('searchbox', { name: 'Search organizations' })
  await search.fill(text(fixtures[10].organizationId))
  await expect(dataRows).toHaveCount(1)
  await expect(dataRows.first()).toHaveAttribute('aria-label', text(fixtures[10].organizationName))
  await expect(page.getByRole('button', { name: 'Previous page', exact: true })).toBeDisabled()
  await search.fill('no-matching-organization')
  await expect(page.getByText('No organizations match your search or filter.')).toBeVisible()
  await search.fill('')
  const filter = page.getByRole('group', { name: 'Filter by workspace access' })
  await filter.getByRole('button', { name: 'Suspended', exact: true }).click()
  await expect(filter.getByRole('button', { name: 'Suspended', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const suspended = rows.map(record).filter(row => row.status === 'SUSPENDED')
  if (suspended.length === 0) await expect(page.getByText('No organizations match your search or filter.')).toBeVisible()
  else await expect(dataRows).toHaveCount(Math.min(suspended.length, 10))
  await expect(overview.getByRole('heading')).toHaveText(metrics)
  await filter.getByRole('button', { name: 'All organizations', exact: true }).click()
  await expect(dataRows).toHaveCount(10)
  const navigation = page.getByRole('navigation', { name: 'Portal feature tabs' })
  await expect(navigation.getByRole('link', { name: /organizations/i })).toHaveAttribute('href', '/platform-admin/organizations')
  await expect(navigation.getByRole('link', { name: /subscriptions/i })).toHaveAttribute('href', '/platform-admin/subscriptions')
  await page.getByRole('button', { name: 'VI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tổ chức', exact: true })).toBeVisible()
  await expect(page.getByRole('searchbox', { name: 'Tìm kiếm tổ chức' })).toBeVisible()
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  expect(observed.errors).toEqual([])
  expect(observed.network).toEqual([])
  await page.getByRole('button', { name: 'User actions menu' }).click()
  await page.getByRole('button', { name: /^(sign out|logout|log out)$/i }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/v1/workspace-auth/current')).status()).toBe(401)
})
