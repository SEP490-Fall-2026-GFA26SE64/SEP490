import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { LearningImportPanel } from './LearningImportPanel'
import { moduleRequest, uploadLearningFile } from '../../../shared/api/moduleAuthoringApi'
vi.mock('../../../shared/i18n/LanguageContext', () => ({ useTranslation: () => ({language:'en'}) }))
vi.mock('../../../shared/api/moduleAuthoringApi', () => ({ moduleRequest:vi.fn(), uploadLearningFile:vi.fn() }))
afterEach(() => { cleanup(); vi.resetAllMocks() })
const batch = {id:'batch',modules:[{moduleId:'MOD-1',excelRow:2,module:{title:'SQL lesson'},lessons:[],expectedVersion:1}],errors:[],ownedDuplicates:['MOD-1'],committed:false}
it('reviews owned duplicates, requires confirmation and commits the existing contract', async () => {
 vi.mocked(uploadLearningFile).mockResolvedValue(batch)
 vi.mocked(moduleRequest).mockResolvedValue({})
 const imported=vi.fn(); render(<LearningImportPanel onImported={imported} />)
 fireEvent.change(screen.getByLabelText('Module import file'),{target:{files:[new File(['test'],'modules.xlsx')]}})
 await screen.findByText('SQL lesson')
 expect(imported).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:'Continue import'}))
 expect(screen.getByText(/Import creates new draft revisions/)).toBeTruthy()
 expect(moduleRequest).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:'Confirm import'}))
 await waitFor(()=>expect(moduleRequest).toHaveBeenCalledWith('/imports/batch/commit','POST',{confirmOwnedDuplicates:true}))
 await waitFor(()=>expect(imported).toHaveBeenCalledOnce())
 expect(screen.getByText('Imported. Submit the drafts for review.')).toBeTruthy()
})
it('blocks an invalid whole batch and preserves the preview after a failed refresh', async () => {
 vi.mocked(uploadLearningFile).mockResolvedValue({...batch,errors:[{moduleId:'MOD-1',row:2,reason:'Skill not eligible'}]})
 vi.mocked(moduleRequest).mockRejectedValue(new Error('Refresh unavailable'))
 render(<LearningImportPanel onImported={vi.fn()} />)
 fireEvent.change(screen.getByLabelText('Module import file'),{target:{files:[new File(['test'],'bad.xlsx')]}})
 await screen.findByText('Skill not eligible')
 expect((screen.getByRole('button',{name:'Continue import'}) as HTMLButtonElement).disabled).toBe(true)
 fireEvent.click(screen.getByRole('button',{name:'Validate again'}))
 expect(await screen.findByRole('alert')).toHaveProperty('textContent','Refresh unavailable')
 expect(screen.getByText('SQL lesson')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Cancel batch'}))
 expect(screen.getByLabelText('Module import file')).toBeTruthy()
})
it('retains the server error on commit and allows a deliberate retry', async () => {
 vi.mocked(uploadLearningFile).mockResolvedValue(batch)
 vi.mocked(moduleRequest).mockRejectedValueOnce(new Error('Batch changed. Refresh validation.')).mockResolvedValueOnce({})
 const imported=vi.fn(); render(<LearningImportPanel onImported={imported} />)
 fireEvent.change(screen.getByLabelText('Module import file'),{target:{files:[new File(['test'],'modules.zip')]}})
 await screen.findByText('SQL lesson')
 fireEvent.click(screen.getByRole('button',{name:'Continue import'}))
 fireEvent.click(screen.getByRole('button',{name:'Confirm import'}))
 expect(await screen.findByRole('alert')).toHaveProperty('textContent','Batch changed. Refresh validation.')
 expect(imported).not.toHaveBeenCalled()
 expect(screen.getByText(/Your modules already exist/)).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Confirm import'}))
 await waitFor(()=>expect(imported).toHaveBeenCalledOnce())
})
it('uploads a dropped ZIP once, blocks further drops while busy and enters Review', async () => {
 let finish!: (value: typeof batch) => void
 vi.mocked(uploadLearningFile).mockReturnValue(new Promise<typeof batch>(resolve => { finish = resolve }))
 render(<LearningImportPanel onImported={vi.fn()} />)
 const file = new File(['zip'], 'module-lessons.zip', {type:'application/zip'})
 const dropzone = screen.getByText('Drag and drop your file here').parentElement!
 fireEvent.dragOver(dropzone, {dataTransfer:{dropEffect:'none'}})
 expect(dropzone.className).toContain('border-primary')
 fireEvent.drop(dropzone, {dataTransfer:{files:[file]}})
 expect(uploadLearningFile).toHaveBeenCalledWith('/imports',file)
 expect((screen.getByRole('button',{name:'Browse files'}) as HTMLButtonElement).disabled).toBe(true)
 fireEvent.drop(dropzone, {dataTransfer:{files:[new File(['x'],'second.xlsx')]}})
 expect(uploadLearningFile).toHaveBeenCalledTimes(1)
 finish(batch)
 expect(await screen.findByText('SQL lesson')).toBeTruthy()
 expect(screen.getByText('module-lessons.zip')).toBeTruthy()
})
it('shows a dropped-file upload error and permits choosing another file', async () => {
 vi.mocked(uploadLearningFile).mockRejectedValueOnce(new Error('Unsupported file format')).mockResolvedValueOnce(batch)
 render(<LearningImportPanel onImported={vi.fn()} />)
 fireEvent.drop(screen.getByText('Drag and drop your file here').parentElement!,{dataTransfer:{files:[new File(['bad'],'bad.txt')]}})
 expect(await screen.findByRole('alert')).toHaveProperty('textContent','Unsupported file format')
 expect((screen.getByRole('button',{name:'Browse files'}) as HTMLButtonElement).disabled).toBe(false)
 expect(screen.getByLabelText('Module import file').getAttribute('accept')).toBe('.xlsx,.zip')
 fireEvent.change(screen.getByLabelText('Module import file'),{target:{files:[new File(['good'],'retry.xlsx')]}})
 expect(await screen.findByText('SQL lesson')).toBeTruthy()
})
